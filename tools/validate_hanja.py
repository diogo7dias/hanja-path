#!/usr/bin/env python3
"""Contract for the served hanja-data.js.

Two callers share this file:

  python3 tools/validate_hanja.py [path]   # exit 1 and print every problem on drift
  import validate_hanja; validate_hanja.validate(payload)   # used by the build

The payload must satisfy BASELINE exactly: the counts, the level split and the
known gaps are the committed truth, so a silent change in any of them fails the
build instead of reaching learners.

Counting rules come in two flavours:
  - absolute baselines (total, level counts, known gaps) live in BASELINE and can
    be overridden per call, which lets tests validate small fixtures;
  - structural rules (uniqueness, ordering, field shape) hold for any payload.
"""
import argparse
import collections
import itertools
import json
import re
import sys
from pathlib import Path

import layout

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_TARGET = ROOT / "hanja-data.js"

PREFIX = "window.HANJA = "
HEADER = "/* hanja-data.js — generated by tools/build.py from the authentic education hanja. */"

CORE_KEYS = ("c", "r", "h", "lv", "idx", "lesson", "lessonPos")
RADICAL_GROUP = ("rad", "radName", "related")
CURATED_GROUP = ("eng", "tip", "s")
HANJA_RE = re.compile(r"[\u4e00-\u9fff]")
HANGUL_RE = re.compile(r"[\uac00-\ud7af]")

LESSON_RANGE = (0, layout.LEVEL_CUTS[0] // layout.LESSON_SIZE - 1)
SLOT_RANGE = (0, layout.LESSON_SIZE - 1)
RADICAL_RANGE = (1, 214)

BASELINE = {
    "total": 1795,
    "level_counts": (600, 600, 595),
    "lesson_size": (5, layout.LESSON_SIZE),
    "max_related": layout.MAX_RELATED,
    "missing_rad": 16,
    "missing_rad_chars": frozenset("萬墨視章直着初最竟卿畓睡垂巡蒸遷"),
    "max_words": layout.MAX_WORDS,
    "missing_words": 23,
    "missing_words_chars": frozenset("產余豐姦龜厥豈稻諒屢梨嘗芽雁予娛淫玆滴慙奚兮鴻"),
    "curated": 22,
    "curated_chars": frozenset("家交國德道力木文法山上生世心愛藥月義人日下學"),
    "non_education_words": frozenset(
        [("月", "월요일", "月曜日"), ("日", "일요일", "日曜日")]
    ),
}


def load_served(path):
    """Read the served file as text, minus the wrapper, as a payload dict."""
    return parse_served(Path(path).read_text(encoding="utf-8"))


def parse_served(text):
    _head, sep, rest = text.partition(PREFIX)
    if not sep:
        raise ValueError("missing the 'window.HANJA = ' wrapper")
    body = rest.rstrip()
    if not body.endswith(";"):
        raise ValueError("missing the trailing semicolon")
    return json.loads(body[:-1])


def validate_text(text):
    """Wrapper rules that must hold for the file exactly as it is written."""
    problems = []
    if not text.startswith(HEADER + "\n"):
        problems.append("first line is not the expected generated-by header")
    if PREFIX not in text:
        problems.append("missing the 'window.HANJA = ' wrapper")
    elif not text.endswith(";\n"):
        problems.append("file does not end with ';\\n'")
    if "\\u" in text:
        problems.append("file contains escaped \\uXXXX; expected ensure_ascii=False")
    return problems


def validate(payload, expect=None):
    """Return a list of problem strings. Empty list means the payload is valid."""
    expect = {**BASELINE, **(expect or {})}
    problems = []

    records = payload.get("hanja", [])
    total = payload.get("total")

    if total != len(records):
        problems.append("total %r does not match %d records" % (total, len(records)))
    if total != expect["total"]:
        problems.append("total %r, expected %d" % (total, expect["total"]))

    levels = payload.get("levels", [])
    counts = tuple(level.get("n") for level in levels)
    if counts != expect["level_counts"]:
        problems.append("level counts %r, expected %r" % (counts, expect["level_counts"]))
    actual = tuple(
        sum(1 for record in records if record.get("lv") == level.get("id"))
        for level in levels
    )
    if actual != counts:
        problems.append("chars per level %r do not match declared levels %r" % (actual, counts))

    for record in records:
        missing = [key for key in CORE_KEYS if key not in record]
        if missing:
            problems.append("character %r is missing %s" % (record.get("c"), ", ".join(missing)))

    chars = [record.get("c") for record in records]
    duplicates = sorted(char for char, count in collections.Counter(chars).items() if count > 1)
    if duplicates:
        problems.append("duplicate characters: %s" % " ".join(duplicates))
    for index, char in enumerate(chars):
        if not isinstance(char, str) or not HANJA_RE.fullmatch(char):
            problems.append("character %r at position %d is not a single CJK ideograph" % (char, index))
    for index, record in enumerate(records):
        if record.get("idx") != index:
            problems.append("position %d has idx %r" % (index, record.get("idx")))
            break

    declared_ids = [level.get("id") for level in levels]
    for index, record in enumerate(records):
        if record.get("lv") not in declared_ids:
            problems.append("character %r has undeclared lv %r" % (record.get("c"), record.get("lv")))
        lesson = record.get("lesson")
        if not isinstance(lesson, int) or not LESSON_RANGE[0] <= lesson <= LESSON_RANGE[1]:
            problems.append(
                "character %r has lesson %r outside %d..%d"
                % (record.get("c"), lesson, LESSON_RANGE[0], LESSON_RANGE[1])
            )
        slot = record.get("lessonPos")
        if not isinstance(slot, int) or not SLOT_RANGE[0] <= slot <= SLOT_RANGE[1]:
            problems.append(
                "character %r has lessonPos %r outside %d..%d"
                % (record.get("c"), slot, SLOT_RANGE[0], SLOT_RANGE[1])
            )

    order = [(record.get("lv"), record.get("lesson"), record.get("lessonPos")) for record in records]
    # keys sort with a missing field first instead of raising on None
    if order != sorted(order, key=lambda key: tuple(-1 if part is None else part for part in key)):
        problems.append("entries are not ordered by lv, then lesson, then lessonPos")

    slot_min, slot_max = expect["lesson_size"]
    for (level_id, lesson_id), group in itertools.groupby(
        records, key=lambda record: (record.get("lv"), record.get("lesson"))
    ):
        entries = list(group)
        slots = [entry.get("lessonPos") for entry in entries]
        if slots != list(range(len(slots))):
            problems.append(
                "level %r lesson %r has non-dense lessonPos %r" % (level_id, lesson_id, slots)
            )
        if not slot_min <= len(entries) <= slot_max:
            problems.append(
                "level %r lesson %r has %d entries, expected %d..%d"
                % (level_id, lesson_id, len(entries), slot_min, slot_max)
            )

    char_set = set(chars)
    rad_by_char = {}
    rad_names = {}
    missing_rad = []
    for record in records:
        present = [key for key in RADICAL_GROUP if key in record]
        if present and len(present) != len(RADICAL_GROUP):
            problems.append(
                "character %r has only %s of rad/radName/related"
                % (record.get("c"), ", ".join(present))
            )
            continue
        if not present:
            missing_rad.append(record.get("c"))
            continue

        number = record.get("rad")
        if not isinstance(number, int) or not RADICAL_RANGE[0] <= number <= RADICAL_RANGE[1]:
            problems.append(
                "character %r has rad %r outside %d..%d"
                % (record.get("c"), number, RADICAL_RANGE[0], RADICAL_RANGE[1])
            )
        name = record.get("radName")
        if not isinstance(name, str) or not HANJA_RE.fullmatch(name):
            problems.append("character %r has radName %r that is not one hanja" % (record.get("c"), name))
        if number in rad_names and name != rad_names[number]:
            problems.append(
                "radName for rad %r is both %r and %r" % (number, rad_names[number], name)
            )
        rad_by_char[record.get("c")] = number
        rad_names[number] = name

    for record in records:
        related = record.get("related")
        if related is None:
            continue
        if not isinstance(related, list):
            problems.append("character %r has related %r, expected a list" % (record.get("c"), related))
            continue
        if len(related) > expect["max_related"]:
            problems.append(
                "character %r has %d related characters, expected at most %d"
                % (record.get("c"), len(related), expect["max_related"])
            )
        for peer in related:
            if peer == record.get("c"):
                problems.append("character %r lists itself under related" % record.get("c"))
            elif peer not in char_set:
                problems.append("character %r has related %r that is not an education character" % (record.get("c"), peer))
            elif rad_by_char.get(peer) != rad_by_char.get(record.get("c")):
                problems.append(
                    "character %r has related %r with a different radical" % (record.get("c"), peer)
                )

    if len(missing_rad) != expect["missing_rad"]:
        problems.append(
            "%d characters omit the radical fields, expected %d"
            % (len(missing_rad), expect["missing_rad"])
        )
    pinned = expect.get("missing_rad_chars")
    if pinned is not None and set(missing_rad) != set(pinned):
        problems.append(
            "characters without radical fields changed: %s" % " ".join(sorted(missing_rad))
        )

    missing_words = []
    curated = []
    outside_education = set()
    for record in records:
        words = record.get("words")
        if words is None:
            missing_words.append(record.get("c"))
        elif not isinstance(words, list) or not words:
            problems.append("character %r has words %r, expected a non-empty list" % (record.get("c"), words))
        else:
            if len(words) > expect["max_words"]:
                problems.append(
                    "character %r has %d words, expected at most %d"
                    % (record.get("c"), len(words), expect["max_words"])
                )
            seen = set()
            for entry in words:
                for key in ("ko", "hj", "gl", "b"):
                    if not isinstance(entry.get(key), str) or not entry.get(key):
                        problems.append(
                            "character %r has an empty %s in word %r" % (record.get("c"), key, entry.get("ko"))
                        )
                reading = entry.get("hj") or ""
                if record.get("c") not in reading:
                    problems.append(
                        "character %r has word %r that does not contain it" % (record.get("c"), reading)
                    )
                if HANGUL_RE.search(entry.get("gl") or ""):
                    problems.append(
                        "character %r has a Hangul gloss %r" % (record.get("c"), entry.get("gl"))
                    )
                if entry.get("ko") in seen:
                    problems.append(
                        "character %r repeats the spelling %r" % (record.get("c"), entry.get("ko"))
                    )
                seen.add(entry.get("ko"))
                for character in reading:
                    if character not in char_set:
                        outside_education.add((record.get("c"), entry.get("ko"), reading))

        present = [key for key in CURATED_GROUP if key in record]
        if present and len(present) != len(CURATED_GROUP):
            problems.append(
                "character %r has only %s of eng/tip/s" % (record.get("c"), ", ".join(present))
            )
        elif present:
            curated.append(record.get("c"))
            sentence = record.get("s")
            if not isinstance(sentence, dict) or not sentence.get("ko") or not sentence.get("en"):
                problems.append(
                    "character %r has an incomplete sentence (needs ko and en)" % record.get("c")
                )

    if len(missing_words) != expect["missing_words"]:
        problems.append(
            "%d characters have no example words, expected %d"
            % (len(missing_words), expect["missing_words"])
        )
    pinned_words = expect.get("missing_words_chars")
    if pinned_words is not None and set(missing_words) != set(pinned_words):
        problems.append(
            "characters without example words changed: %s" % " ".join(sorted(missing_words))
        )

    if len(curated) != expect["curated"]:
        problems.append(
            "%d characters carry the curated trio, expected %d" % (len(curated), expect["curated"])
        )
    pinned_curated = expect.get("curated_chars")
    if pinned_curated is not None and set(curated) != set(pinned_curated):
        problems.append("curated characters changed: %s" % " ".join(sorted(curated)))

    allowed = expect.get("non_education_words")
    if allowed is not None:
        unexpected = outside_education - set(allowed)
        if unexpected:
            problems.append(
                "example words use characters outside the education set: %s"
                % ", ".join("/".join(entry) for entry in sorted(unexpected))
            )

    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description="Validate the served hanja-data.js against its contract.")
    parser.add_argument("path", nargs="?", default=str(DEFAULT_TARGET), help="file to validate")
    args = parser.parse_args(argv)

    try:
        text = Path(args.path).read_text(encoding="utf-8")
        payload = parse_served(text)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print("FAIL %s: %s" % (args.path, exc))
        return 1

    problems = validate_text(text) + validate(payload)
    if problems:
        print("FAIL %s: %d problem(s)" % (args.path, len(problems)))
        for problem in problems:
            print("  -", problem)
        return 1

    counts = "/".join(str(level["n"]) for level in payload["levels"])
    print("ok %s: %d records, levels %s" % (args.path, payload["total"], counts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
